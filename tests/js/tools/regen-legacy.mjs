/**
 * Rewrite tests/js/innerhtml-legacy.mjs from the current admin sources.
 *
 * Run from the repository root:
 *
 *     node tests/js/tools/regen-legacy.mjs
 *
 * The LEGACY map should only shrink.  Regenerate after a merge that brings in
 * template-literal code the lint flags (the offenders are then a merge
 * artefact), or after fixing sites, to drop the entries that no longer exist.
 * Never regenerate to hide a new offender in code you wrote: wrap the value in
 * esc()/jsArg()/raw(), or use html`` + render() from core/html.js.
 *
 * Keys are `file::normalized expression`, with an occurrence count; line
 * numbers are never recorded, so the output is stable under unrelated edits.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';

import { keyCounts, scanSource } from '../innerhtml-scan.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ADMIN_JS = join(
  HERE,
  '../../../packages/llm-rosetta-gateway/src/llm_rosetta_gateway/admin/js',
);
const OUT = join(HERE, '../innerhtml-legacy.mjs');

function adminFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) out.push(...adminFiles(path));
    else if (entry.endsWith('.js')) out.push(path);
  }
  return out.sort();
}

const items = [];
for (const file of adminFiles(ADMIN_JS)) {
  for (const { expr } of scanSource(readFileSync(file, 'utf8'))) {
    items.push({ file: relative(ADMIN_JS, file), expr });
  }
}
const counts = keyCounts(items);
const keys = Object.keys(counts).sort();

let out = `/**
 * The innerHTML interpolations that predate the escaping lint.
 *
 * Generated by \`node tests/js/tools/regen-legacy.mjs\`; do not edit by hand.
 * Each key is \`file::expression\` (no line numbers, so an edit above does not
 * invalidate it); the value is how many times it occurs.  The list can only
 * shrink: innerhtml-lint.test.mjs fails when a new offender appears and when an
 * entry here no longer exists, so a fix must delete its line (rerun the
 * script).  Fix an entry by wrapping the value in esc() / jsArg() / raw(), or
 * by moving the template to html\`\` + render() (core/html.js).
 *
 * Most entries are a local that was escaped where it was built (\`time\`,
 * \`detailId\`) or a number/class name; they are listed because the scanner
 * reads what the assignment spells out, not where a variable came from.
 */
export const LEGACY = {
`;
for (const k of keys) out += `  ${JSON.stringify(k)}: ${counts[k]},\n`;
out += '};\n';
writeFileSync(OUT, out);
console.log(`${items.length} offenders, ${keys.length} entries -> ${relative(process.cwd(), OUT)}`);
